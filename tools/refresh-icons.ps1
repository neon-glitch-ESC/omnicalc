# OmniCalc - icon subset refresh utility (no build toolchain required, optional)
# Regenerates: assets/fonts/material-symbols-outlined.woff2 and js/icons.js
# Uses only public Google Fonts endpoints. Run: powershell -ExecutionPolicy Bypass -File tools/refresh-icons.ps1

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$ua = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'

# ---- Icon names used across the app (add new names here, then rerun) ----
$icons = @(
  'home','calculate','science','code','show_chart','grid_on','account_balance','event',
  'currency_exchange','currency_bitcoin','diamond','straighten','weight','category',
  'thermostat','square_foot','speed','schedule','compress','local_fire_department','bolt',
  'fitness_center','rotate_right','air','opacity','water','local_gas_station','sd_storage',
  'network_check','aspect_ratio','architecture','dangerous','monitor_heart','restaurant',
  'apparel','history_edu','pin','extension','settings','menu','close','search','star',
  'star_border','dark_mode','light_mode','swap_vert','swap_horiz','refresh','delete','add',
  'download','upload','content_copy','check','arrow_forward','arrow_back','expand_more',
  'expand_less','info','warning','trending_up','timer','sync','offline_bolt','key','tune',
  'palette','database','shield','visibility','edit','backspace','functions','table_chart',
  'history','save','link','calendar_month','update','restart_alt','chevron_right','print',
  'check_circle','cancel','error','help','language','equal','percent','tag','priority_high'
)

# ---- Fetch official codepoints table ----
$cpUrl = 'https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints'
Write-Host "Fetching codepoints table..."
$cpText = (Invoke-WebRequest -UseBasicParsing -Uri $cpUrl -TimeoutSec 60).Content
$cpMap = @{}
foreach ($line in ($cpText -split "`n")) {
  $parts = $line.Trim() -split '\s+'
  if ($parts.Count -ge 2) { $cpMap[$parts[0]] = $parts[1] }
}

$map = [ordered]@{}
$chars = New-Object System.Text.StringBuilder
$missing = @()
foreach ($name in $icons) {
  if ($cpMap.ContainsKey($name)) {
    $cp = $cpMap[$name]
    $map[$name] = $cp
    [void]$chars.Append([char][Convert]::ToInt32($cp, 16))
  } else { $missing += $name }
}

if ($missing.Count -gt 0) { Write-Warning ("Icons not found in Material Symbols: " + ($missing -join ', ')) }

# ---- Write js/icons.js ----
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Auto-generated by tools/refresh-icons.ps1 -- Material Symbols codepoint map (subset font). */')
[void]$sb.AppendLine('window.OC = window.OC || {};')
[void]$sb.AppendLine('OC.ICONS = OC.ICONS || {};')
foreach ($k in $map.Keys) {
  [void]$sb.AppendLine(("OC.ICONS['" + $k + "'] = '\u" + $map[$k].ToLower() + "';"))
}
Set-Content -Path (Join-Path $root 'js\icons.js') -Value $sb.ToString() -Encoding UTF8
Write-Host ("Wrote js/icons.js with " + $map.Count + " icons.")

# ---- Fetch subsetted font CSS ----
$text = [uri]::EscapeDataString($chars.ToString())
$cssUrl = 'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200&display=block&text=' + $text
Write-Host "Requesting subset font CSS..."
$css = (Invoke-WebRequest -UseBasicParsing -Headers @{'User-Agent'=$ua} -Uri $cssUrl -TimeoutSec 60).Content
$m = [regex]::Match($css, 'url\((https://[^)]+)\)')
if (-not $m.Success) { throw 'Could not parse font URL from Google Fonts CSS response.' }
$fontUrl = $m.Groups[1].Value
$ur = [regex]::Match($css, 'unicode-range:\s*([^;]+);')
$unicodeRange = if ($ur.Success) { $ur.Groups[1].Value.Trim() } else { '' }

Invoke-WebRequest -UseBasicParsing -Uri $fontUrl -OutFile (Join-Path $root 'assets\fonts\material-symbols-outlined.woff2') -TimeoutSec 120
$size = (Get-Item (Join-Path $root 'assets\fonts\material-symbols-outlined.woff2')).Length
Write-Host ("Downloaded subset font: " + [math]::Round($size/1024,1) + " KB (unicode-range: " + $unicodeRange + ")")

# ---- Write css/fonts.css ----
$fontCss = @"
/* ------------------------------------------------------------------
   OmniCalc local fonts. This file is auto-generated by
   tools/refresh-icons.ps1 (icon subset) -- the @import for text fonts
   loads from Google Fonts and is cached by the service worker.
   ------------------------------------------------------------------ */
@import url('https://fonts.googleapis.com/css2?family=Playfair+Display:ital,wght@0,500;0,700;0,900;1,400;1,600&family=Fira+Code:wght@400;500;600&display=swap');

@font-face {
  font-family: 'Material Symbols Outlined';
  font-style: normal;
  font-weight: 100 700;
  font-display: block;
  src: url('../assets/fonts/material-symbols-outlined.woff2') format('woff2');
  unicode-range: $unicodeRange;
}
"@
Set-Content -Path (Join-Path $root 'css\fonts.css') -Value $fontCss -Encoding UTF8
Write-Host 'Wrote css/fonts.css. Done.'
